private void searchInventory(String keyword) {
    DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
    model.setRowCount(0);

    String sql = "SELECT product, price, stock, type, brand, size "
               + "FROM inventory "
               + "WHERE product LIKE ? OR brand LIKE ? "
               + "OR type LIKE ? OR size LIKE ? "
               + "ORDER BY id DESC";

    try (Connection con = DBconnection.connect();
         PreparedStatement pst = con.prepareStatement(sql)) {

        String search = "%" + keyword.trim() + "%";

        pst.setString(1, search);
        pst.setString(2, search);
        pst.setString(3, search);
        pst.setString(4, search);

        try (ResultSet rs = pst.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("product"),
                    String.format("₱%.2f", rs.getDouble("price")),
                    rs.getInt("stock"),
                    rs.getString("type"),
                    rs.getString("brand"),
                    rs.getString("size")
                });
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Error searching inventory: " + e.getMessage()
        );
    }
}

    
   private void loadInventory() {

    DefaultTableModel model =
        (DefaultTableModel) jTable2.getModel();

    model.setRowCount(0);

    String sql =
        "SELECT product, type, brand, size, price, stock "
      + "FROM inventory "
      + "ORDER BY id DESC";

    try {

        Connection con = DBconnection.connect();

        if (con == null) {
            JOptionPane.showMessageDialog(
                this,
                "Unable to connect to database.",
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        PreparedStatement pst = con.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        while (rs.next()) {

            String product = rs.getString("product");
            String type = rs.getString("type");
            String brand = rs.getString("brand");
            String size = rs.getString("size");

            double price = rs.getDouble("price");
            int stock = rs.getInt("stock");

            model.addRow(new Object[]{
                product,
                String.format("₱%.2f", price),
                stock,
                type,
                brand,
                size
            });
        }

        rs.close();
        pst.close();
        con.close();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Unable to load inventory:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }
}

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
      if (!userSession.isAdmin()) {
    JOptionPane.showMessageDialog(
        this,
        "Access Denied! Only administrators can add or update inventory.",
        "Access Denied",
        JOptionPane.ERROR_MESSAGE
    );
    return;
}  // TODO add your handling code here:
    String product = jTextField2.getText().trim();
    String priceText = jTextField3.getText().trim();
    String stockText = jTextField4.getText().trim();
    String type = jTextField5.getText().trim();
    String brand = jTextField6.getText().trim();
    String size = jTextField7.getText().trim();

 
      
if (product.isEmpty() ||
    priceText.isEmpty() ||
    stockText.isEmpty() ||
    type.isEmpty() ||
    brand.isEmpty() ||
    size.isEmpty()) {

    JOptionPane.showMessageDialog(
        this,
        "Please fill in all fields.",
        "Missing Information",
        JOptionPane.WARNING_MESSAGE
    );

    return;
}



    try {

        double price = Double.parseDouble(
            priceText
                .replace("₱", "")
                .replace(",", "")
                .trim()
        );

        int stockToAdd = Integer.parseInt(stockText);

        if (price < 0) {
            JOptionPane.showMessageDialog(
                this,
                "Price cannot be negative.",
                "Invalid Price",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        if (stockToAdd <= 0) {
            JOptionPane.showMessageDialog(
                this,
                "Stock to add must be greater than 0.",
                "Invalid Stock",
                JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        Connection con = DBconnection.connect();

        if (con == null) {
            JOptionPane.showMessageDialog(
                this,
                "Unable to connect to database.",
                "Database Error",
                JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        int selectedRow = jTable2.getSelectedRow();

        // ==========================================
        // EXISTING PRODUCT
        // ==========================================
        if (selectedRow >= 0) {

            String sql =
                "UPDATE inventory " +
                "SET stock = stock + ?, price = ? " +
                "WHERE product = ? " +
                "AND type = ? " +
                "AND brand = ? " +
                "AND size = ?";

            PreparedStatement pst = con.prepareStatement(sql);

            pst.setInt(1, stockToAdd);
            pst.setDouble(2, price);
            pst.setString(3, product);
            pst.setString(4, type);
            pst.setString(5, brand);
            pst.setString(6, size);

            int updated = pst.executeUpdate();

            pst.close();

            if (updated > 0) {

                JOptionPane.showMessageDialog(
                    this,
                    "Stock added successfully!"
                );

            } else {

                JOptionPane.showMessageDialog(
                    this,
                    "Product was not found.",
                    "Update Error",
                    JOptionPane.WARNING_MESSAGE
                );
            }

        // ==========================================
        // NEW PRODUCT
        // ==========================================
        } else {

            String sql =
                "INSERT INTO inventory " +
                "(product, type, brand, size, price, stock) " +
                "VALUES (?, ?, ?, ?, ?, ?)";

            PreparedStatement pst = con.prepareStatement(sql);

            pst.setString(1, product);
            pst.setString(2, type);
            pst.setString(3, brand);
            pst.setString(4, size);
            pst.setDouble(5, price);
            pst.setInt(6, stockToAdd);

            pst.executeUpdate();

            pst.close();

            JOptionPane.showMessageDialog(
                this,
                "New product added successfully!"
            );
        }

        con.close();

        // Refresh table
        loadInventory();

        // Clear fields
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
        jTextField5.setText("");
        jTextField6.setText("");
        jTextField7.setText("");

        // Remove selected row
        jTable2.clearSelection();

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Price and Stock must contain numbers only.",
            "Invalid Input",
            JOptionPane.WARNING_MESSAGE
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Database Error:\n" + e.getMessage(),
            "Database Error",
            JOptionPane.ERROR_MESSAGE
        );

        e.printStackTrace();
    }


        

    }//GEN-LAST:event_jButton2ActionPerformed

